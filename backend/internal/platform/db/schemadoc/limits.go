package schemadoc

import (
	"fmt"
	"strconv"
	"strings"
	"time"

	"relaylab/internal/platform/config"
)

type limitRow struct{ env, value, what string }

// Limits renders the production defaults of every limit and timeout as a
// Markdown table, read from the configuration loaders themselves (nothing
// here is a copy of a number).
func Limits() (string, error) {
	empty := func(string) string { return "" }
	prod := config.EnvProduction
	cfg, err := config.Load(func(k string) string {
		return map[string]string{
			"APP_ENV": "production", "APP_ORIGIN": "https://relaylab.example.com",
			"DATABASE_URL": "postgres://u:p@db.example.com/relaylab?sslmode=require",
		}[k]
	})
	if err != nil {
		return "", err
	}
	replay, err := config.LoadReplay(empty, prod)
	if err != nil {
		return "", err
	}
	retention, err := config.LoadRetention(empty, prod)
	if err != nil {
		return "", err
	}
	demo, err := config.LoadDemo(empty, prod)
	if err != nil {
		return "", err
	}
	outbound, err := config.LoadOutbound(empty, cfg)
	if err != nil {
		return "", err
	}

	var rows []limitRow
	for _, d := range config.LimitDocs() {
		rows = append(rows, limitRow{d.Env, strconv.Itoa(d.Default), d.Doc})
	}
	n := strconv.Itoa
	dur := func(d time.Duration) string { return d.String() }
	rows = append(rows,
		limitRow{"STREAM_REVALIDATE_INTERVAL", dur(cfg.StreamRevalidate), "How often a live event stream re-checks its session and project"},
		limitRow{"REPLAY_PROJECT_CONCURRENCY", n(replay.ProjectConcurrency), "Replays running at once per project"},
		limitRow{"REPLAY_PROJECT_QUEUE_DEPTH", n(replay.ProjectQueueDepth), "Replays waiting or running per project"},
		limitRow{"REPLAY_USER_RATE_PER_MINUTE", n(replay.UserRatePerMinute), "Replays one user may create per minute"},
		limitRow{"REPLAY_MAX_TRIES", n(replay.MaxTries), "Deliveries per replay"},
		limitRow{"REPLAY_RESPONSE_EXCERPT_BYTES", n(replay.ResponseExcerptBytes), "Response body kept with a replay, in bytes"},
		limitRow{"OUTBOUND_CONNECT_TIMEOUT", dur(outbound.ConnectTimeout), "Replay: TCP connect and each DNS lookup"},
		limitRow{"OUTBOUND_TLS_TIMEOUT", dur(outbound.TLSHandshakeTimeout), "Replay: TLS handshake"},
		limitRow{"OUTBOUND_HEADER_TIMEOUT", dur(outbound.ResponseHeaderTimeout), "Replay: waiting for response headers"},
		limitRow{"OUTBOUND_TOTAL_TIMEOUT", dur(outbound.TotalTimeout), "Replay: the whole request, body included"},
		limitRow{"OUTBOUND_MAX_RESPONSE_BYTES", n(outbound.MaxResponseBytes), "Replay: response body read, in bytes"},
		limitRow{"OUTBOUND_MAX_CONCURRENCY", n(outbound.MaxConcurrency), "Replay requests in flight per worker"},
		limitRow{"OUTBOUND_ALLOWED_PORTS", joinInts(outbound.AllowedPorts), "Replay destination ports"},
		limitRow{"RETENTION_EVENT_TTL", dur(retention.EventTTL), "Events (and their replays) are deleted after this long"},
		limitRow{"RETENTION_MAX_EVENTS_PER_PROJECT", n(retention.MaxEventsPerProject), "Events kept per project; the oldest beyond are deleted"},
		limitRow{"RETENTION_AUDIT_TTL", dur(retention.AuditTTL), "Audit log entries are deleted after this long"},
		limitRow{"RETENTION_JOB_TTL", dur(retention.JobTTL), "Finished background jobs are deleted after this long"},
		limitRow{"DEMO_TTL", dur(demo.TTL), "Demo workspaces and their data are deleted after this long"},
		limitRow{"DEMO_MAX_PROJECTS", n(demo.MaxProjects), "Projects per demo user"},
		limitRow{"DEMO_MAX_ENDPOINTS", n(demo.MaxEndpoints), "Endpoints per demo project"},
		limitRow{"DEMO_MAX_EVENTS", n(demo.MaxEvents), "Events kept per demo project"},
		limitRow{"DEMO_MAX_STREAMS", n(demo.MaxStreams), "Live streams per demo user"},
		limitRow{"DEMO_INGEST_RATE_PER_MINUTE", n(demo.IngestPerMinute), "Webhooks per minute a demo endpoint accepts"},
	)
	var b strings.Builder
	b.WriteString("Production defaults, generated by `cmd/schemadoc` from the configuration code. Do not edit by hand: run `pnpm docs:generate`.\n\n")
	b.WriteString("| Setting | Default | Limits |\n|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", r.env, r.value, r.what)
	}
	return b.String(), nil
}

func joinInts(ns []int) string {
	s := make([]string, len(ns))
	for i, v := range ns {
		s[i] = strconv.Itoa(v)
	}
	return strings.Join(s, ", ")
}
