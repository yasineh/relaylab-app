// Package schemadoc renders the canonical listing of RelayLab's database
// schema and configuration limits for the documentation
// (add-project-documentation). The ERD and the security doc embed these
// listings between marker comments; tests regenerate them and fail on any
// difference, so the docs cannot drift from the migrations or the defaults.
package schemadoc

import (
	"context"
	"fmt"
	"strings"

	"github.com/jackc/pgx/v5"
)

// Schemas are the documented schemas: Better Auth's, then goose's.
var Schemas = []string{"auth", "app"}

// Begin and End mark a generated block in a Markdown file.
func Begin(name string) string { return "<!-- schemadoc:" + name + ":begin -->" }
func End(name string) string   { return "<!-- schemadoc:" + name + ":end -->" }

// Table is one table's listing.
type Table struct {
	Schema, Name string
	Columns      []Column
	Constraints  []string // "name: definition", sorted by name
	Indexes      []string // index definitions, sorted by name
}

// Column is one column.
type Column struct {
	Name, Type, Default string
	NotNull             bool
}

// Read returns every table of the documented schemas from conn.
func Read(ctx context.Context, conn *pgx.Conn) ([]Table, error) {
	rows, err := conn.Query(ctx, `
		SELECT n.nspname, c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
		       COALESCE(pg_get_expr(d.adbin, d.adrelid), '')
		FROM pg_attribute a
		JOIN pg_class c ON c.oid = a.attrelid
		JOIN pg_namespace n ON n.oid = c.relnamespace
		LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
		WHERE c.relkind = 'r' AND n.nspname = ANY($1) AND a.attnum > 0 AND NOT a.attisdropped
		ORDER BY array_position($1, n.nspname::text), c.relname, a.attnum`, Schemas)
	if err != nil {
		return nil, fmt.Errorf("read columns: %w", err)
	}
	var tables []Table
	index := map[string]int{}
	for rows.Next() {
		var schema, table string
		var col Column
		if err := rows.Scan(&schema, &table, &col.Name, &col.Type, &col.NotNull, &col.Default); err != nil {
			return nil, err
		}
		key := schema + "." + table
		i, ok := index[key]
		if !ok {
			i = len(tables)
			index[key] = i
			tables = append(tables, Table{Schema: schema, Name: table})
		}
		tables[i].Columns = append(tables[i].Columns, col)
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}
	for i := range tables {
		t := &tables[i]
		qualified := pgx.Identifier{t.Schema, t.Name}.Sanitize()
		if t.Constraints, err = strings2(ctx, conn, `
			SELECT conname || ': ' || pg_get_constraintdef(oid) FROM pg_constraint
			WHERE conrelid = $1::regclass ORDER BY conname`, qualified); err != nil {
			return nil, err
		}
		if t.Indexes, err = strings2(ctx, conn, `
			SELECT indexdef FROM pg_indexes WHERE schemaname = $1 AND tablename = $2 ORDER BY indexname`, t.Schema, t.Name); err != nil {
			return nil, err
		}
	}
	return tables, nil
}

func strings2(ctx context.Context, conn *pgx.Conn, sql string, args ...any) ([]string, error) {
	rows, err := conn.Query(ctx, sql, args...)
	if err != nil {
		return nil, err
	}
	return pgx.CollectRows(rows, pgx.RowTo[string])
}

// Markdown renders tables as the generated ERD listing.
func Markdown(tables []Table) string {
	var b strings.Builder
	b.WriteString("Generated by `cmd/schemadoc` from a database with every migration applied (Better Auth, then goose). Do not edit by hand: run `pnpm docs:generate`.\n")
	for _, t := range tables {
		fmt.Fprintf(&b, "\n#### `%s.%s`\n\n", t.Schema, t.Name)
		b.WriteString("| Column | Type | Null | Default |\n|---|---|---|---|\n")
		for _, c := range t.Columns {
			null := "yes"
			if c.NotNull {
				null = "no"
			}
			def := ""
			if c.Default != "" {
				def = "`" + strings.ReplaceAll(c.Default, "|", `\|`) + "`"
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s |\n", c.Name, c.Type, null, def)
		}
		if len(t.Constraints) > 0 {
			b.WriteString("\nConstraints:\n\n")
			for _, c := range t.Constraints {
				fmt.Fprintf(&b, "- `%s`\n", c)
			}
		}
		if len(t.Indexes) > 0 {
			b.WriteString("\nIndexes:\n\n")
			for _, ix := range t.Indexes {
				fmt.Fprintf(&b, "- `%s`\n", ix)
			}
		}
	}
	return b.String()
}

// Replace swaps the named generated block in doc for body. It fails if the
// markers are missing.
func Replace(doc, name, body string) (string, error) {
	begin, end := Begin(name), End(name)
	i := strings.Index(doc, begin)
	j := strings.Index(doc, end)
	if i < 0 || j < i {
		return "", fmt.Errorf("markers %s ... %s not found", begin, end)
	}
	return doc[:i+len(begin)] + "\n" + strings.TrimSpace(body) + "\n" + doc[j:], nil
}

// Block returns the current content of the named generated block.
func Block(doc, name string) (string, bool) {
	begin, end := Begin(name), End(name)
	i := strings.Index(doc, begin)
	j := strings.Index(doc, end)
	if i < 0 || j < i {
		return "", false
	}
	return strings.TrimSpace(doc[i+len(begin) : j]), true
}
