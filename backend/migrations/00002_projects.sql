-- Projects: the ownership and isolation boundary for every later resource
-- (add-project-management). Owners are Better Auth users, so the auth migrations
-- must run first (`pnpm migrate` and the compose/production migrate jobs do).
--
-- Permanent deletion contract (D18): every later project-scoped table MUST
-- reference app.projects(id) ON DELETE CASCADE. Deleting a user cascades to
-- their projects, and from there to everything inside them.

-- +goose Up
-- +goose StatementBegin
DO $$
BEGIN
  IF to_regclass('auth."user"') IS NULL THEN
    RAISE EXCEPTION 'auth."user" does not exist: run the auth migrations (pnpm --filter @relaylab/auth migrate) before the app migrations';
  END IF;
END
$$;
-- +goose StatementEnd

CREATE TABLE app.projects (
  id          uuid PRIMARY KEY, -- UUIDv7, generated by the API
  owner_id    text NOT NULL REFERENCES auth."user" (id) ON DELETE CASCADE,
  name        text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
  description text CHECK (description IS NULL OR char_length(description) <= 500),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Serves the owner-scoped list (newest first) and the per-owner count.
CREATE INDEX projects_owner_created_idx ON app.projects (owner_id, created_at DESC);

COMMENT ON TABLE app.projects IS 'User-owned projects; deleting one cascades to all project-scoped data';

-- +goose Down
DROP TABLE app.projects;
