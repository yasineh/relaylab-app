-- Webhook receiving endpoints and the shared audit log (add-endpoint-management).
--
-- Endpoint tokens are never stored in plaintext (D4): token_hash is
-- HMAC-SHA256(ENDPOINT_TOKEN_HMAC_KEY, token) for O(1) lookup during ingestion,
-- and token_ciphertext is AES-256-GCM(ENDPOINT_TOKEN_ENC_KEY, token) so the
-- owner can see the receiving URL again.
--
-- Deletion contract (D18): both tables cascade from app.projects.

-- +goose Up
CREATE TABLE app.endpoints (
  id                uuid PRIMARY KEY, -- UUIDv7, generated by the API
  project_id        uuid NOT NULL REFERENCES app.projects (id) ON DELETE CASCADE,
  name              text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
  token_hash        bytea NOT NULL CHECK (octet_length(token_hash) = 32),
  token_ciphertext  bytea NOT NULL,
  token_key_version smallint NOT NULL DEFAULT 1,
  enabled           boolean NOT NULL DEFAULT true,
  last_received_at  timestamptz, -- set by ingestion
  token_rotated_at  timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT endpoints_token_hash_key UNIQUE (token_hash)
);

CREATE INDEX endpoints_project_created_idx ON app.endpoints (project_id, created_at DESC);

COMMENT ON TABLE app.endpoints IS 'Webhook receiving endpoints; tokens stored only as HMAC hash + AES-GCM ciphertext';

CREATE TABLE app.audit_log (
  id            uuid PRIMARY KEY, -- UUIDv7
  project_id    uuid NOT NULL REFERENCES app.projects (id) ON DELETE CASCADE,
  actor_user_id text REFERENCES auth."user" (id) ON DELETE SET NULL,
  action        text NOT NULL CHECK (char_length(action) BETWEEN 1 AND 64),
  resource_type text NOT NULL CHECK (char_length(resource_type) BETWEEN 1 AND 64),
  resource_id   uuid,
  metadata      jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX audit_log_project_created_idx ON app.audit_log (project_id, created_at DESC, id DESC);

COMMENT ON TABLE app.audit_log IS 'Who did what to which project resource; never contains secrets, tokens, or payloads';

-- +goose Down
DROP TABLE app.audit_log;
DROP TABLE app.endpoints;
